import { WORKFLOW_ANSWER_TOOL } from '../openchamber-control/actions.js';
import {
  AGENT_TOOL_ACTION_TITLES,
  CODE_MODE_CATALOG_LINES,
  EXEMPT_CALLBACK_FROM_PROXY_SOURCE,
  SECRET_RUN_HELPERS_SOURCE,
  TOOL_SCHEMA_VERSION,
  managedToolSpecs,
  toolInputPreparation,
} from './runtime.js';

/**
 * The managed agent tools as a Pi extension: the source of one self-contained
 * ES module whose default export `(pi) => void` registers the same tools as the
 * OpenCode plugin (`createPluginSource` in ./runtime.js), with the same names,
 * descriptions, input schemas and input normalization. Both generators build
 * from `managedToolSpecs` and `toolInputPreparation`, so none of that can drift.
 *
 * What changes with the agent is only the transport glue, written here:
 *
 * - Pi validates a tool's input against its schema before `execute` runs, so
 *   the generated tool carries the same schema the plugin gives OpenCode.
 * - `execute(toolCallId, params, signal, onUpdate, ctx)` takes the session id
 *   from `ctx.sessionManager`, sends `callID: toolCallId`, and returns the
 *   server's envelope as text with `details.openchamber`, which the chat reads
 *   from the stored result where the plugin put `metadata.openchamber`.
 * - Tools behind Code Mode register with `exposure: 'codemode'`, which Pi does
 *   not activate on its own; the extension activates Pi's `codemode` tool when
 *   it registers one. The others register `direct`.
 * - Pi has no `session.prompt` hook; its `input` event fires for every prompt,
 *   steer and follow-up, which ends the calls that wait for the user's answer.
 * - Pi has no permission system. `secret.run` asks the gate a sibling extension
 *   of the same Pi process installs as `globalThis.__openchamberPiPermission`.
 *
 * `PI-EXTENSION.md` has the reasons.
 */

// Written into the generated file, where the next person to open it finds the
// one contract it leaves to its caller.
const GENERATED_FILE_HEADER = `// Generated by OpenChamber. Registers its managed agent tools in Pi; edits are overwritten.
//
// Environment: OPENCHAMBER_AGENT_TOOL_URL and OPENCHAMBER_AGENT_TOOL_TOKEN, the
// callback address and bearer token of the OpenChamber server that started Pi.
//
// secret.run permission: Pi has no permission system, so before the call
// reaches OpenChamber this file awaits globalThis.__openchamberPiPermission(request)
// when a sibling extension of the same Pi process has installed one, and
// refuses secret.run when none is installed. The request is
//   { sessionID, toolCallId, tool, action: "shell", resources: [commandLine],
//     save: ["<program> *"], signal }
// Reject by throwing: the error text reaches the agent as the tool's failure.
`;

const toolLabel = (name) => (
  name === 'openchamber' ? 'OpenChamber' : `OpenChamber ${name.replace(/^openchamber_/, '').replaceAll('_', ' ')}`
);

const toolRegistrationSource = (spec) => {
  const { inputSchema, prepareSource } = toolInputPreparation(spec);
  const namespaceDescription = spec.codeMode ? CODE_MODE_CATALOG_LINES[spec.name] : undefined;
  return `  registerManagedTool(pi, {
    name: ${JSON.stringify(spec.name)},
    label: ${JSON.stringify(toolLabel(spec.name))},
    description: ${JSON.stringify(spec.description)},
    parameters: ${JSON.stringify(inputSchema)},
    exposure: ${JSON.stringify(spec.codeMode ? 'codemode' : 'direct')},${spec.definitions.length > 1
      ? `
    actions: ${JSON.stringify(spec.definitions.map(({ action }) => action))},`
      : ''}${namespaceDescription
      ? `
    namespace: ${JSON.stringify({ name: spec.name, description: namespaceDescription })},`
      : ''}${spec.name === WORKFLOW_ANSWER_TOOL
      ? `
    defaultActive: false,`
      : ''}
    prepare(args) {
${prepareSource}    },${spec.answers
      ? `
    waits: (args) => (${spec.answers.waitsWhen}),
    closedInChatNote: ${JSON.stringify(spec.answers.closedInChatNote)},`
      : ''}${spec.secretRun
      ? `
    secretRun: true,`
      : ''}
  })
`;
};

// The tools' shared behavior. Template literals stay out of it so it reads the
// same here and in the generated file.
const RUNTIME_SOURCE = String.raw`
// Session id -> abort controllers of the calls that wait for the user's answer
// (a page, or a secret card).
const waitingForChat = new Map()

// The callback is one POST, and node:http carries it. Not fetch: Pi installs a
// global dispatcher that ends a request with no response after its idle
// timeout (httpIdleTimeoutMs, 5 minutes by default), and a card waits as long
// as the user takes. A fresh agent per request keeps every socket default off.
const postJson = (endpoint, token, body, signal) => new Promise((resolve, reject) => {
  const url = new URL(endpoint)
  const request = (url.protocol === "https:" ? https : http).request(url, {
    method: "POST",
    agent: false,
    headers: {
      authorization: "Bearer " + token,
      "content-type": "application/json",
      "content-length": Buffer.byteLength(body),
    },
    signal,
  }, (response) => {
    const chunks = []
    response.on("data", (chunk) => chunks.push(chunk))
    response.on("error", reject)
    response.on("end", () => resolve({ status: response.statusCode, text: Buffer.concat(chunks).toString("utf8") }))
  })
  request.on("error", reject)
  request.end(body)
})

// Models routinely drop the namespace their tool's name appears to supply:
// memory.read is sent as read. The server resolves that inside the calling
// tool's own actions, but Pi checks the action against the schema first and
// would refuse the bare name, so the same resolution runs before the check.
const canonicalAction = (actions, requested) => {
  const value = requested.trim()
  if (actions.includes(value)) return value
  const matches = actions.filter((action) => action.slice(action.indexOf(".") + 1) === value)
  return matches.length === 1 ? matches[0] : requested
}

const registerManagedTool = (pi, tool) => {
  pi.registerTool({
    name: tool.name,
    label: tool.label,
    description: tool.description,
    parameters: tool.parameters,
    exposure: tool.exposure,
    ...(tool.namespace ? { namespace: tool.namespace } : {}),
    ...(tool.defaultActive === false ? { defaultActive: false } : {}),
    ...(tool.actions ? {
      prepareArguments: (args) => (typeof args?.action === "string" ? { ...args, action: canonicalAction(tool.actions, args.action) } : args),
    } : {}),
    async execute(toolCallId, params, signal, onUpdate, ctx) {
      // Models routinely put the inputs next to the action instead of inside
      // the parameters object, and dropping them there produced a
      // "url is required" error for a call that plainly carried a url. Both
      // shapes are accepted; an explicit parameters object wins on a conflict.
      const { action: requestedAction, parameters, ...flattened } = params ?? {}
      const args = { ...flattened, ...(parameters ?? {}), action: requestedAction }
      tool.prepare(args)
      const title = Object.hasOwn(ACTION_TITLES, args.action) ? ACTION_TITLES[args.action] : args.action
      const details = (extra) => ({ openchamber: { schemaVersion: SCHEMA_VERSION, action: args.action, description: title, ...extra } })
      const progress = (extra) => onUpdate?.({ content: [], details: details(extra) })
      // An envelope that says ok: false is still a result, not a failed call:
      // the chat reads details.openchamber.ok, and the agent reads the envelope.
      const outcome = (text, extra) => ({ content: [{ type: "text", text }], details: details(extra), isError: false })
      const failure = (payload) => outcome(JSON.stringify(payload), { ok: false })
      progress()
      const endpoint = process.env.OPENCHAMBER_AGENT_TOOL_URL
      const token = process.env.OPENCHAMBER_AGENT_TOOL_TOKEN
      if (!endpoint || !token) {
        return failure({ schemaVersion: SCHEMA_VERSION, ok: false, action: args.action, error: { message: "OpenChamber managed tool connection is unavailable" } })
      }
      // The server resolves the session's directory from this id, and secret and
      // knowledge actions belong to it, so a call that cannot name it goes nowhere.
      const piSessionID = ctx?.sessionManager?.getSessionId?.()
      if (typeof piSessionID !== "string" || piSessionID === "") {
        return failure({ schemaVersion: SCHEMA_VERSION, ok: false, action: args.action, error: { message: "OpenChamber could not tell which session called this tool", kind: "runtime" } })
      }
      const sessionID = piSessionID.startsWith("ses") ? piSessionID : "ses_" + piSessionID
      // secret.run asks for the user's approval of its command line before the
      // call reaches OpenChamber, so a request for the secrets of a command the
      // user would not let run never appears. The check sits before the wait is
      // registered, so nothing waits on a call that was refused. A refusal the
      // gate throws is not caught: it ends the call as the tool's failure.
      if (tool.secretRun && args.action === "secret.run") {
        const command = secretRunCommand(args)
        if (command.error) return failure({ schemaVersion: SCHEMA_VERSION, ok: false, action: args.action, error: { message: command.error, kind: "usage" } })
        const gate = globalThis.__openchamberPiPermission
        if (typeof gate !== "function") {
          return failure({ schemaVersion: SCHEMA_VERSION, ok: false, action: args.action, error: { message: "OpenChamber cannot ask the user to approve a command here, so secret.run is unavailable; use secret.request", kind: "runtime" } })
        }
        await gate({
          sessionID,
          toolCallId,
          tool: tool.name,
          action: "shell",
          resources: [secretRunCommandLine(command.program, command.args)],
          save: [command.program + " *"],
          signal,
        })
      }
      // A call that waits for the user's answer holds the session's chat: a
      // message the user writes meanwhile reaches Pi only after the call returns.
      // So it registers under its session, and the input event aborts it when
      // any prompt for the session arrives. The call then returns "answered in
      // the chat" and the agent reads the message next.
      const chatController = new AbortController()
      if (tool.waits?.(args) === true) {
        const set = waitingForChat.get(sessionID) ?? new Set()
        set.add(chatController)
        waitingForChat.set(sessionID, set)
      }
      try {
        const response = await postJson(
          endpoint,
          token,
          JSON.stringify({ input: args, sessionID, callID: toolCallId, tool: tool.name }),
          AbortSignal.any([signal, chatController.signal].filter(Boolean)),
        )
        let result = null
        try { result = JSON.parse(response.text) } catch {}
        const valid = result?.schemaVersion === SCHEMA_VERSION && typeof result?.ok === "boolean" && typeof result?.action === "string"
        progress({ ok: valid && result.ok === true })
        if (valid) {
          // The answer also lands in the call's details, which Pi stores, so
          // every client shows the page as answered after a reload.
          const answer = tool.waits && result.ok === true && result.data && typeof result.data.answer === "object" && result.data.answer !== null ? { answer: result.data.answer } : {}
          return outcome(response.text, { ok: result.ok === true, ...answer })
        }
        return failure({ schemaVersion: SCHEMA_VERSION, ok: false, action: args.action, error: { message: "OpenChamber returned an invalid response", kind: "runtime", status: response.status } })
      } catch (error) {
        if (chatController.signal.aborted && !signal?.aborted) {
          const answer = { answered: false, reason: "chat" }
          progress({ ok: true })
          return outcome(JSON.stringify({ schemaVersion: SCHEMA_VERSION, ok: true, action: args.action, data: { answer, note: tool.closedInChatNote } }), { ok: true, answer })
        }
        return failure({ schemaVersion: SCHEMA_VERSION, ok: false, action: args.action, error: { message: error instanceof Error ? error.message : String(error), kind: "runtime" } })
      } finally {
        const set = waitingForChat.get(sessionID)
        if (set) {
          set.delete(chatController)
          if (set.size === 0) waitingForChat.delete(sessionID)
        }
      }
    },
  })
}
`;

const ABORT_WAITS_ON_INPUT_SOURCE = `  pi.on("input", (_event, ctx) => {
    const piSessionID = ctx.sessionManager.getSessionId()
    const sessionID = piSessionID.startsWith("ses") ? piSessionID : "ses_" + piSessionID
    for (const controller of waitingForChat.get(sessionID) ?? []) controller.abort()
    return { action: "continue" }
  })
`;

// Registering a codemode tool does not make Pi declare its codemode tool, and
// scripts reach the tools only through it. Active tools are set once the
// session exists, and every start (new, resume, reload) asks again.
const ACTIVATE_CODEMODE_SOURCE = `  pi.on("session_start", () => {
    const active = pi.getActiveTools()
    if (!active.includes("codemode")) pi.setActiveTools([...active, "codemode"])
  })
`;

/**
 * @param {object} options  The capability flags `createPluginSource` takes:
 *   includeControl, includeSchedule, includeWeb, includeMemory,
 *   includeKnowledge, includeNotify, includeRender, includeImage,
 *   includeSecret, includeUsage and includeWorkflow.
 * @returns {string} Source of the extension module.
 */
export const createPiManagedToolsExtensionSource = (options) => {
  const specs = managedToolSpecs(options);
  const hasWaitingTool = specs.some((spec) => spec.answers);
  const hasCodeModeTool = specs.some((spec) => spec.codeMode);
  return `${GENERATED_FILE_HEADER}import http from "node:http"
import https from "node:https"

const SCHEMA_VERSION = ${TOOL_SCHEMA_VERSION}
const ACTION_TITLES = ${JSON.stringify(AGENT_TOOL_ACTION_TITLES)}

${specs.some((spec) => spec.secretRun) ? SECRET_RUN_HELPERS_SOURCE : ''}${EXEMPT_CALLBACK_FROM_PROXY_SOURCE}${RUNTIME_SOURCE}
export default (pi) => {
  exemptCallbackFromProxy()
${specs.map(toolRegistrationSource).join('')}${hasWaitingTool ? ABORT_WAITS_ON_INPUT_SOURCE : ''}${hasCodeModeTool ? ACTIVATE_CODEMODE_SOURCE : ''}}
`;
};
